/**
 * Emotes: small 11x11 icons drawn above a character's head.
 *
 * The art below is fill only. `outlined` adds a 1-pixel `steel.0` ring around every
 * shape (8-neighbour), which is what keeps an emote readable on any background.
 * Inner ink (eyes, dots) is written as `0` and is left as is.
 * Anchor is bottom-centre [5, 11], so an emote drawn at a head's top sits right above it.
 */
import { slotIndex } from '../../core/palette';
import { sprite, type Sprite } from '../../core/sprite';

const INK = slotIndex('steel.0');

/** Parse fill art and ring every shape with a 1-pixel ink outline. */
function outlined(art: string): Sprite {
  const s = sprite(art, { anchor: [5, 11] });
  const px = new Uint8Array(s.px);
  const at = (x: number, y: number) => (x < 0 || y < 0 || x >= s.w || y >= s.h ? 0 : s.px[y * s.w + x]!);
  for (let y = 0; y < s.h; y++) {
    for (let x = 0; x < s.w; x++) {
      if (s.px[y * s.w + x] !== 0) continue;
      let near = false;
      for (let dy = -1; dy <= 1 && !near; dy++) for (let dx = -1; dx <= 1; dx++) if (at(x + dx, y + dy)) near = true;
      if (near) px[y * s.w + x] = INK;
    }
  }
  return { ...s, px };
}

